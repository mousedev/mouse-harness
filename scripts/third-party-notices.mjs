#!/usr/bin/env node
// Generate THIRD_PARTY_NOTICES.md: the production dependency tree of the three
// published packages (core, opencode, cli), with each package's name, version,
// license field, and LICENSE text as installed under node_modules. Dev
// dependencies are excluded: they never ship. The CLI bundle
// (packages/cli/dist/mouse.mjs) inlines this whole tree, so the notices apply
// to the bundle as well as to the npm packages. Plain Node, no dependencies.
//
//   pnpm install --frozen-lockfile --ignore-scripts
//   node scripts/third-party-notices.mjs        # writes THIRD_PARTY_NOTICES.md
//   node scripts/third-party-notices.mjs --check  # exit 1 if the file is stale
import { existsSync, readdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PUBLISHED = ["packages/core", "packages/opencode", "packages/cli"].map((p) =>
  path.join(ROOT, p),
);
const OUT = path.join(ROOT, "THIRD_PARTY_NOTICES.md");
const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;

function readJson(file) {
  return JSON.parse(readFileSync(file, "utf8"));
}

/** Node-style lookup of `name` starting from `fromDir` and walking up. */
function resolvePackageDir(name, fromDir) {
  let dir = fromDir;
  for (;;) {
    const candidate = path.join(dir, "node_modules", name);
    if (existsSync(path.join(candidate, "package.json"))) return realpathSync(candidate);
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

function licenseText(dir) {
  const file = readdirSync(dir).find((f) => LICENSE_FILE.test(f));
  return file ? readFileSync(path.join(dir, file), "utf8").trim() : null;
}

function licenseField(pkg) {
  if (typeof pkg.license === "string") return pkg.license;
  if (pkg.license?.type) return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type ?? l).join(" OR ");
  return "UNKNOWN";
}

/** Walk production deps; workspace packages are traversed but not listed. */
function collect() {
  const found = new Map(); // "name@version" -> { name, version, license, text, requiredBy }
  const seenWorkspace = new Set();

  function visit(dir) {
    const pkg = readJson(path.join(dir, "package.json"));
    const deps = { ...(pkg.dependencies ?? {}), ...(pkg.optionalDependencies ?? {}) };
    for (const [name, spec] of Object.entries(deps)) {
      const depDir = resolvePackageDir(name, dir);
      if (!depDir) {
        if (pkg.optionalDependencies?.[name]) continue; // optional and not installed here
        throw new Error(`${pkg.name}: cannot resolve production dependency ${name}@${spec}`);
      }
      const depPkg = readJson(path.join(depDir, "package.json"));
      const isWorkspace =
        spec.startsWith("workspace:") || depDir.startsWith(`${ROOT}${path.sep}packages`);
      if (isWorkspace) {
        if (seenWorkspace.has(depDir)) continue;
        seenWorkspace.add(depDir);
        visit(depDir);
        continue;
      }
      const key = `${depPkg.name}@${depPkg.version}`;
      if (found.has(key)) {
        found.get(key).requiredBy.add(pkg.name);
        continue;
      }
      found.set(key, {
        name: depPkg.name,
        version: depPkg.version,
        license: licenseField(depPkg),
        homepage:
          depPkg.homepage ??
          (typeof depPkg.repository === "string" ? depPkg.repository : depPkg.repository?.url) ??
          null,
        text: licenseText(depDir),
        requiredBy: new Set([pkg.name]),
      });
      visit(depDir);
    }
  }

  for (const dir of PUBLISHED) {
    seenWorkspace.add(realpathSync(dir));
    visit(dir);
  }
  return [...found.values()].sort((a, b) =>
    a.name === b.name ? a.version.localeCompare(b.version) : a.name.localeCompare(b.name),
  );
}

function render(entries) {
  const lines = [
    "# Third-party notices",
    "",
    "Production dependencies shipped by `@mousedev/harness-core`, `@mousedev/harness-opencode`,",
    "and `@mousedev/harness` (the CLI bundle `mouse.mjs` inlines all of them). Development",
    "dependencies are not included. Generated by `node scripts/third-party-notices.mjs`;",
    "do not edit by hand.",
    "",
    "| Package | Version | License | Required by |",
    "| --- | --- | --- | --- |",
  ];
  for (const e of entries) {
    lines.push(
      `| ${e.name} | ${e.version} | ${e.license} | ${[...e.requiredBy].sort().join(", ")} |`,
    );
  }
  lines.push("");
  for (const e of entries) {
    lines.push(`## ${e.name}@${e.version}`, "");
    lines.push(`License: ${e.license}`);
    if (e.homepage) lines.push(`Source: ${e.homepage.replace(/^git\+/, "").replace(/\.git$/, "")}`);
    lines.push("");
    if (e.text) {
      lines.push("```", e.text, "```");
    } else {
      lines.push(`No LICENSE file is shipped in the package; see the \`license\` field above.`);
    }
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

const output = render(collect());
if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== output) {
    process.stderr.write(
      "THIRD_PARTY_NOTICES.md is stale; run node scripts/third-party-notices.mjs\n",
    );
    process.exit(1);
  }
  process.stdout.write("THIRD_PARTY_NOTICES.md is up to date\n");
} else {
  writeFileSync(OUT, output);
  process.stdout.write(
    `wrote ${path.relative(ROOT, OUT)} (${output.split("\n## ").length - 1} packages)\n`,
  );
}
